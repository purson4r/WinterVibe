#[cfg(test)]
mod tests {
    use super::Language;

    #[test]
    fn new_install_defaults_to_russian() {
        assert_eq!(Language::from_registry(None), Language::Russian);
    }

    #[test]
    fn language_registry_values_round_trip() {
        for language in [Language::Russian, Language::English] {
            assert_eq!(Language::from_registry(Some(language.registry_value())), language);
        }
    }

    #[test]
    fn unknown_language_value_defaults_to_russian() {
        assert_eq!(Language::from_registry(Some(u32::MAX)), Language::Russian);
    }
}
