#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Language {
    #[default]
    Russian,
    English,
}

impl Language {
    pub fn from_registry(value: Option<u32>) -> Language {
        match value {
            Some(1) => Language::English,
            Some(0) | None => Language::Russian,
            Some(_) => Language::Russian,
        }
    }

    #[allow(dead_code)]
    pub fn registry_value(self) -> u32 {
        match self {
            Language::Russian => 0,
            Language::English => 1,
        }
    }

    pub fn strings(self) -> &'static Strings {
        match self {
            Language::Russian => &RUSSIAN,
            Language::English => &ENGLISH,
        }
    }
}

